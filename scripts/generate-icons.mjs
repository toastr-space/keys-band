// Writes src/lib/icons.ts with the SVG data of every icon the UI uses, taken from the
// @iconify-json packages, so extension pages never download icons at runtime.
// Run after adding or changing an icon: node scripts/generate-icons.mjs
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const srcDir = join(root, 'src');
const outFile = join(srcDir, 'lib', 'icons.ts');

const walk = (dir) =>
	readdirSync(dir).flatMap((name) => {
		const path = join(dir, name);
		return statSync(path).isDirectory() ? walk(path) : [path];
	});

// icon names appear as string literals such as "mdi:check" in components
const used = new Set();
for (const file of walk(srcDir).filter((f) => f.endsWith('.svelte'))) {
	for (const [, name] of readFileSync(file, 'utf8').matchAll(/['"]([a-z0-9]+(?:-[a-z0-9]+)*:[a-z0-9]+(?:-[a-z0-9]+)*)['"]/g))
		used.add(name);
}

const sets = new Map();
const loadSet = (prefix) => {
	if (!sets.has(prefix)) {
		const dir = join(root, 'node_modules', '@iconify-json', prefix);
		sets.set(prefix, {
			icons: JSON.parse(readFileSync(join(dir, 'icons.json'), 'utf8')),
			info: JSON.parse(readFileSync(join(dir, 'info.json'), 'utf8'))
		});
	}
	return sets.get(prefix);
};

const resolve = (set, name) => {
	const icon = set.icons.icons[name];
	if (icon) return icon;
	const alias = set.icons.aliases?.[name];
	if (!alias) return null;
	if (alias.rotate || alias.hFlip || alias.vFlip) throw new Error(`Transformed alias not supported: ${name}`);
	const parent = resolve(set, alias.parent);
	return parent && { ...parent, ...alias };
};

const output = {};
for (const full of [...used].sort()) {
	const [prefix, name] = full.split(':');
	const set = loadSet(prefix);
	const icon = resolve(set, name);
	if (!icon) throw new Error(`Icon not found: ${full}`);
	output[full] = {
		body: icon.body,
		width: icon.width ?? set.icons.width ?? 16,
		height: icon.height ?? set.icons.height ?? 16
	};
}

const credits = [...sets.entries()]
	.map(([prefix, { info }]) => `//   ${prefix}: ${info.name}, ${info.license.title}, ${info.author.name}`)
	.join('\n');

writeFileSync(
	outFile,
	`// Generated by ${relative(root, new URL(import.meta.url).pathname)}. Do not edit.\n` +
		`// Icon data from the @iconify-json packages:\n${credits}\n\n` +
		`export interface IconData {\n\tbody: string;\n\twidth: number;\n\theight: number;\n}\n\n` +
		`export const icons: Record<string, IconData> = ${JSON.stringify(output, null, '\t')};\n`
);
console.log(`Wrote ${Object.keys(output).length} icons to ${relative(root, outFile)}`);
